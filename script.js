/* ================= VARIABLES ================= */

const pages =
  document.querySelectorAll(".page");

const navigationButtons =
  document.querySelectorAll("[data-page]");

const emotionCards =
  document.querySelectorAll(".emotion-card");

const songList =
  document.querySelector("#song-list");

let currentEmotion = "";

let queue = [];

let currentSongIndex = 0;


/* ================= PAGE NAVIGATION ================= */

function showPage(pageId) {

  pages.forEach(function(page) {

    page.classList.remove("active-page");

  });


  const selectedPage =
    document.querySelector(
      "#" + pageId
    );


  if (selectedPage) {

    selectedPage.classList.add(
      "active-page"
    );

    window.scrollTo({
      top: 0,
      behavior: "smooth"
    });

  }

}


navigationButtons.forEach(function(button) {

  button.addEventListener(
    "click",
    function() {

      showPage(
        button.dataset.page
      );

    }
  );

});


/* ================= EMOTION PAGE ================= */

emotionCards.forEach(function(card) {

  card.addEventListener(
    "click",
    function() {

      currentEmotion =
        card.dataset.emotion;

      displayEmotionPage();

      showPage("emotion-page");

    }
  );

});


function displayEmotionPage() {

  const data =
    moodData[currentEmotion];


  document.querySelector(
    "#emotion-emoji"
  ).textContent =
    data.emoji;


  document.querySelector(
    "#emotion-title"
  ).textContent =
    data.title;


  document.querySelector(
    "#emotion-description"
  ).textContent =
    data.description;


  displaySongs();

}


document
  .querySelector("#back-home")
  .addEventListener(
    "click",
    function() {

      showPage("home");

    }
  );


/* ================= SONG CARDS ================= */

function displaySongs() {

  songList.innerHTML = "";


  const songs =
    moodData[currentEmotion].songs;


  songs.forEach(
    function(song, index) {

      const songCard =
        document.createElement("button");


      songCard.className =
        "song-card";


      songCard.innerHTML = `

        <div class="song-number">

          ${String(index + 1).padStart(2, "0")}

        </div>


        <div class="song-info">

          <h3>
            ${song.title}
          </h3>

          <p class="artist">
            ${song.artist}
          </p>


          <div class="song-reason">

            <strong>
              ✨ Why this song fits
            </strong>

            ${song.reason}

          </div>

        </div>


        <div class="play-arrow">
          Play →
        </div>

      `;


      songCard.addEventListener(
        "click",
        function() {

          startSession(index);

        }
      );


      songList.appendChild(
        songCard
      );

    }
  );

}


/* ================= SHUFFLE ================= */

function shuffle(array) {

  const newArray =
    [...array];


  for (
    let i =
      newArray.length - 1;

    i > 0;

    i--
  ) {

    const randomIndex =
      Math.floor(
        Math.random() *
        (i + 1)
      );


    [
      newArray[i],
      newArray[randomIndex]
    ] =
    [
      newArray[randomIndex],
      newArray[i]
    ];

  }


  return newArray;

}


/* ================= START SESSION ================= */

function startSession(songIndex) {

  const songs =
    moodData[currentEmotion].songs;


  const selectedSong =
    songs[songIndex];


  const remainingSongs =
    songs.filter(
      function(song, index) {

        return index !== songIndex;

      }
    );


  queue = [

    selectedSong,

    ...shuffle(remainingSongs)

  ];


  currentSongIndex = 0;


  displayPlayer();

  showPage("player-page");

}


/* ================= PLAYER ================= */

function displayPlayer() {

  const song =
    queue[currentSongIndex];


  const emotion =
    moodData[currentEmotion];


  document.querySelector(
    "#player-emoji"
  ).textContent =
    emotion.emoji;


  document.querySelector(
    "#player-title"
  ).textContent =
    song.title;


  document.querySelector(
    "#player-artist"
  ).textContent =
    song.artist;


  document.querySelector(
    "#player-reason"
  ).textContent =
    song.reason;


  document.querySelector(
    "#song-position"
  ).textContent =

    `${currentSongIndex + 1} / ${queue.length}`;


  const searchQuery =
    encodeURIComponent(
      song.title +
      " " +
      song.artist
    );


  document.querySelector(
    "#spotify-link"
  ).href =

    `https://open.spotify.com/search/${searchQuery}`;


  displayQueue();

}


/* ================= QUEUE ================= */

function displayQueue() {

  const queueList =
    document.querySelector(
      "#queue-list"
    );


  queueList.innerHTML = "";


  queue
    .slice(currentSongIndex + 1)
    .forEach(
      function(song, index) {

        const queueItem =
          document.createElement("div");


        queueItem.className =
          "queue-item";


        queueItem.innerHTML = `

          <span>

            ${String(
              index + 1
            ).padStart(2, "0")}

          </span>


          <div>

            <strong>
              ${song.title}
            </strong>

            <p>
              ${song.artist}
            </p>

          </div>

        `;


        queueList.appendChild(
          queueItem
        );

      }
    );

}


/* ================= NEXT SONG ================= */

document
  .querySelector("#next-button")
  .addEventListener(
    "click",
    function() {

      if (
        currentSongIndex <
        queue.length - 1
      ) {

        currentSongIndex++;

        displayPlayer();

      }

      else {

        currentSongIndex = 0;

        queue =
          shuffle(queue);

        displayPlayer();

      }

    }
  );


/* ================= RESHUFFLE ================= */

document
  .querySelector("#reshuffle-button")
  .addEventListener(
    "click",
    function() {

      const currentSong =
        queue[currentSongIndex];


      const remainingSongs =
        queue.slice(
          currentSongIndex + 1
        );


      queue = [

        ...queue.slice(
          0,
          currentSongIndex + 1
        ),

        ...shuffle(
          remainingSongs
        )

      ];


      displayPlayer();

    }
  );


/* ================= BACK TO SONGS ================= */

document
  .querySelector("#back-to-emotion")
  .addEventListener(
    "click",
    function() {

      showPage("emotion-page");

    }
  );


